#!/usr/bin/env python3
"""Generate web/src/engine/dns-presets.mjs from xray_forge/core/dns_presets.py.

The browser app shows the same DNS catalog as the desktop app; this keeps it a single source.

    python tools/gen_web_dns.py          # rewrite
    python tools/gen_web_dns.py --check  # exit 1 if the committed file is stale
"""

from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
OUT = ROOT / "web" / "src" / "engine" / "dns-presets.mjs"


def render() -> str:
    from xray_forge.core import dns_presets as d
    return (
        "// GENERATED by tools/gen_web_dns.py from xray_forge/core/dns_presets.py. Do not edit.\n"
        f"export const DNS_CATEGORIES = {json.dumps(list(d.CATEGORIES), indent=2, ensure_ascii=False)};\n"
        f"export const DNS_PRESETS = {json.dumps(list(d.PRESETS), indent=2, ensure_ascii=False)};\n"
    )


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    text = render()
    if "--check" in argv:
        return 0 if OUT.is_file() and OUT.read_text(encoding="utf-8") == text else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
