#!/usr/bin/env python3
"""Generate web/src/engine/unicode-tables.mjs from this Python's Unicode database.

The web app's JavaScript port must treat whitespace and digits exactly like the
Python engine (str.strip/split/isdigit, int()), including non-ASCII digits such
as the Persian/Arabic-Indic ones people really paste into ports.

    python tools/gen_web_unicode.py          # rewrite
    python tools/gen_web_unicode.py --check  # exit 1 if the committed file is stale
"""

from __future__ import annotations

import pathlib
import sys
import unicodedata

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "web" / "src" / "engine" / "unicode-tables.mjs"


def ranges(points):
    out, start, prev = [], None, None
    for p in points:
        if start is None:
            start = prev = p
        elif p == prev + 1:
            prev = p
        else:
            out.append((start, prev))
            start = prev = p
    if start is not None:
        out.append((start, prev))
    return out


def fmt(rs):
    return "[" + ",".join(f"{a},{b}" for a, b in rs) + "]"


def render() -> str:
    allcp = range(0x110000)
    space = [c for c in allcp if chr(c).isspace()]
    # isdigit() but not isdecimal(): superscripts, circled digits... (int() rejects them)
    digit_only = [c for c in allcp if chr(c).isdigit() and not chr(c).isdecimal()]
    decimal = [c for c in allcp if chr(c).isdecimal()]
    zeros = []
    for c in decimal:
        if unicodedata.decimal(chr(c)) == 0:
            zeros.append(c)
    # every decimal digit must sit in a run of ten above its zero
    for z in zeros:
        assert all(unicodedata.decimal(chr(z + i)) == i for i in range(10)), hex(z)
    assert sum(1 for c in decimal) == 10 * len(zeros)
    return (
        "// GENERATED by tools/gen_web_unicode.py from Python "
        f"{sys.version_info.major}.{sys.version_info.minor} (Unicode {unicodedata.unidata_version}). Do not edit.\n"
        "// Flat [lo, hi, lo, hi, ...] code point ranges.\n"
        f"export const SPACE = {fmt(ranges(space))};\n"
        f"export const DIGIT_ONLY = {fmt(ranges(digit_only))};\n"
        f"export const DECIMAL_ZEROS = [{','.join(str(z) for z in zeros)}];\n"
    )


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    text = render()
    if "--check" in argv:
        if sys.version_info[:2] != (3, 13):
            print("skipped: the tables are generated with Python 3.13")
            return 0
        return 0 if OUT.is_file() and OUT.read_text(encoding="utf-8") == text else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
